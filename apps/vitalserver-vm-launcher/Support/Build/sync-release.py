#!/usr/bin/env python3
import json
import re
import sys
from pathlib import Path


def require_service(release, key):
    try:
        return release["services"][key]
    except KeyError as error:
        raise SystemExit(f"missing release service field: {key}.{error}") from error


def write_if_changed(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def replace(pattern, replacement, content):
    next_content, count = re.subn(pattern, replacement, content, count=1, flags=re.MULTILINE)
    if count != 1:
        raise SystemExit(f"release sync pattern did not match: {pattern}")
    return next_content


def sync_swift(root, release):
    helper_version = release["helperVersion"]
    min_updater_version = release["minUpdaterVersion"]
    vitalserver = require_service(release, "vitalServer")
    redis = require_service(release, "redis")
    redis_ui = require_service(release, "redisUI")
    swagger_ui = require_service(release, "swaggerUI")
    guest_edge = require_service(release, "guestEdge")
    host_proxy = require_service(release, "hostProxy")

    write_if_changed(
        root / "Sources/HostRuntimeControl/Runtime/GeneratedVersion.swift",
        f"""// Generated from apps/vitalserver-vm-launcher/release.json by make vm-version-source.
// Do not edit this file directly.

extension Constants {{
    static let launcherVersion = "{helper_version}"
}}
""",
    )
    write_if_changed(
        root / "Sources/VitalServerHelperApp/GeneratedRelease.swift",
        f"""// Generated from apps/vitalserver-vm-launcher/release.json by make vm-version-source.
// Do not edit this file directly.

enum GeneratedRelease {{
    static let helperVersion = "{helper_version}"
    static let minUpdaterVersion = "{min_updater_version}"
    static let vitalServerVersion = "{release["vitalServerVersion"]}"
    static let vitalServerImage = "{vitalserver["image"]}"
    static let redisImage = "{redis["image"]}"
    static let redisUIImage = "{redis_ui["image"]}"
    static let swaggerUIImage = "{swagger_ui["image"]}"
    static let guestEdgeImage = "{guest_edge["image"]}"
    static let hostProxyImage = "{host_proxy["image"]}"
    static let redisVersion = "{redis["version"]}"
    static let redisUIVersion = "{redis_ui["version"]}"
    static let swaggerUIVersion = "{swagger_ui["version"]}"
    static let guestEdgeVersion = "{guest_edge["version"]}"
    static let hostProxyVersion = "{host_proxy["version"]}"
}}
""",
    )


def sync_compose(root, release):
    compose = root / "Support/Guest/compose.yaml"
    content = compose.read_text(encoding="utf-8")
    replacements = {
        r"image: redis:[^\n]+": f"image: {require_service(release, 'redis')['image']}",
        r"image: vitalserver:[^\n]+": f"image: {require_service(release, 'vitalServer')['image']}",
        r"image: ghcr\.io/joeferner/redis-commander:[^\n]+": f"image: {require_service(release, 'redisUI')['image']}",
        r"image: swaggerapi/swagger-ui:[^\n]+": f"image: {require_service(release, 'swaggerUI')['image']}",
        r"image: nginx:[^\n]+": f"image: {require_service(release, 'guestEdge')['image']}",
    }
    for pattern, replacement in replacements.items():
        content = replace(pattern, replacement, content)
    write_if_changed(compose, content)


def sync_build_config(root, release):
    config = root / "Support/Build/vm-build.toml"
    content = config.read_text(encoding="utf-8")
    replacements = {
        r'"vitalserver:[^"]+"': f'"{require_service(release, "vitalServer")["image"]}"',
        r'"redis:[^"]+"': f'"{require_service(release, "redis")["image"]}"',
        r'"ghcr\.io/joeferner/redis-commander:[^"]+"': f'"{require_service(release, "redisUI")["image"]}"',
        r'"swaggerapi/swagger-ui:[^"]+"': f'"{require_service(release, "swaggerUI")["image"]}"',
        r'"nginx:[^"]+"': f'"{require_service(release, "guestEdge")["image"]}"',
        r'expected_version = "nginx/[^"]+"': f'expected_version = "{require_service(release, "hostProxy")["image"]}"',
    }
    for pattern, replacement in replacements.items():
        content = replace(pattern, replacement, content)
    write_if_changed(config, content)


def sync_guest_scripts(root, release):
    bootstrap = root / "Support/Guest/bootstrap.sh"
    content = bootstrap.read_text(encoding="utf-8")
    content = replace(
        r"docker image inspect vitalserver:[^ ]+",
        f"docker image inspect {require_service(release, 'vitalServer')['image']}",
        content,
    )
    write_if_changed(bootstrap, content)

    repair_datastore = root / "Support/Guest/bin/tirosh-vitalserver-repair-datastore"
    content = repair_datastore.read_text(encoding="utf-8")
    content = replace(
        r"\n    redis:[^ ]+ \\\n",
        f"\n    {require_service(release, 'redis')['image']} \\\n",
        content,
    )
    write_if_changed(repair_datastore, content)


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: sync-release.py <launcher-dir>")
    root = Path(sys.argv[1])
    release = json.loads((root / "release.json").read_text(encoding="utf-8"))
    sync_swift(root, release)
    sync_compose(root, release)
    sync_build_config(root, release)
    sync_guest_scripts(root, release)


if __name__ == "__main__":
    main()
